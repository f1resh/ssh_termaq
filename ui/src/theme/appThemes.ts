/**
 * Built-in application (chrome/UI) themes. Every AppThemeColors key maps to a CSS variable
 * (bgElevated -> --bg-elevated, see applyTheme.ts). Each theme names the terminal scheme it pairs with
 * (`defaultScheme`, used when the global terminal scheme is 'auto').
 *
 * Palettes follow the upstream theme definitions (Nord, Dracula, Solarized, Gruvbox, Catppuccin, GitHub
 * Primer, Tokyo Night, One Dark Pro); UI-only shades (hover/active/borders) are derived to keep contrast
 * readable at small sizes.
 */
import type { AppTheme, AppThemeColors } from '@shared/types';

function theme(id: string, name: string, variant: AppTheme['variant'], defaultScheme: string, colors: AppThemeColors): AppTheme {
  return { id, name, variant, defaultScheme, colors };
}

